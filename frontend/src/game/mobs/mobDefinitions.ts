export function getMob(id: string): Mob | undefined {
  return mobDefinitions[id];
}

export function getMobsByDungeon(dungeonId: string): Mob[] {
  return Object.values(mobDefinitions).filter((mob) => mob.dungeonId === dungeonId);
}

export function getNextMobId(currentMobId: string, dungeonId: string): string | null {
  const dungeon = getDungeon(dungeonId);
  if (!dungeon || dungeon.pool.length === 0) return null;
  const index = dungeon.pool.indexOf(currentMobId);
  // ponytail: cycles the pool in order; weighted/random selection if variety feels samey
  return dungeon.pool[(index + 1) % dungeon.pool.length] ?? dungeon.pool[0];
}